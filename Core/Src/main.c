/**
  * @brief  The application entry point.
  * @retval int
  */
int main(void)
{

  /* USER CODE BEGIN 1 */

  /* USER CODE END 1 */

  /* MCU Configuration--------------------------------------------------------*/

  /* Reset of all peripherals, Initializes the Flash interface and the Systick. */
  HAL_Init();

  /* USER CODE BEGIN Init */

  /* USER CODE END Init */

  /* Configure the system clock */
  SystemClock_Config();

  /* USER CODE BEGIN SysInit */

  /* USER CODE END SysInit */

  /* Initialize all configured peripherals */
  MX_GPIO_Init();
  MX_TIM3_Init();
  MX_USART2_UART_Init();
  MX_TIM2_Init();
  MX_ADC_Init();
  MX_I2C1_Init();
  /* USER CODE BEGIN 2 */
  HCSR04_Init(&hc1, &htim3, TIM_CHANNEL_2, TRIG_PIN_GPIO_Port, TRIG_PIN_Pin);

  // timer enkodera
  HAL_TIM_Encoder_Start(&htim2, TIM_CHANNEL_ALL);

  // wartość pocz. 50, min 2, max 400, 4 impulsy na klik
  Encoder_Init(&enc_dist, &htim2, 50, 2, 400, 4);

  lcd_init();

  uint8_t last_detection = 2;   // Pamięć stanu (0-brak, 1-jest, 2-start)

  uint32_t last_sensor_read = 0;
  uint32_t last_ui_update = 0;
  uint8_t update_needed = 1;
  /* USER CODE END 2 */

  /* Infinite loop */
  /* USER CODE BEGIN WHILE */
  while (1)
  {
	// Sprawdź enkoder i od razu ustaw flagę, jeśli kręcono gałką
	if (Encoder_Update(&enc_dist))
	{
		update_needed = 1;
	}

	// Odczyt potencjometru
	uint16_t new_tolerance = Get_Tolerance_From_ADC();
	if (new_tolerance != tolerance)
	{
		tolerance = new_tolerance;
		update_needed = 1;
	}

	// Pomiar czujnikiem (odświeżany co 100ms)
	if (HAL_GetTick() - last_sensor_read >= 100)
	{
		HCSR04_Trigger(&hc1);
		last_sensor_read = HAL_GetTick();
	}

	// Sprawdź, czy stan detekcji się zmienił
	int16_t blad = (int16_t)hc1.Distance - enc_dist.current_value;
	uint8_t current_detection = (abs(blad) <= tolerance);

	if (current_detection != last_detection)
	{
		update_needed = 1;
		last_detection = current_detection; // Zapamiętany nowy stan
	}

	// Odświerzanie interfaceu (MAX 20 FPS)
	// Rysuj tylko, jeśli zaszła zmiana ORAZ minęło 40ms od ostatniego rysowania
	if (update_needed && (HAL_GetTick() - last_ui_update >= 50))
	{
		Update_Interface(hc1.Distance, enc_dist.current_value, tolerance, current_detection);

		last_ui_update = HAL_GetTick(); // Reset stoper ekranu
		update_needed = 0;              // Zmiana flagi dopiero PO narysowaniu
	}

    /* USER CODE END WHILE */

    /* USER CODE BEGIN 3 */
  }
  /* USER CODE END 3 */
}

