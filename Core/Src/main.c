uint16_t Get_Tolerance_From_ADC(void)
{
	static uint32_t last_adc_val = 0;
	uint16_t tol = 1; // Wartość domyślna

	HAL_ADC_Start(&hadc);
	if (HAL_ADC_PollForConversion(&hadc, 10) == HAL_OK)
	{
		uint32_t current_adc_val = HAL_ADC_GetValue(&hadc);

		// Histereza
		if (abs((int32_t)current_adc_val - (int32_t)last_adc_val) > 40)
		{
			last_adc_val = current_adc_val;
		}

		// Dead-zones dla 12-bitowego ADC (0-4095)
		if (last_adc_val > 4000)
		{
			// Prawie maksymalnie w prawo - block na 20
			tol = 20;
		}
		else if (last_adc_val < 50)
		{
			// Prawie maksymalnie w lewo -> block na 1
			tol = 1;
		}
		else
		{
			// Środkowa, liniowa część obrotu gałki
			tol = 1 + (last_adc_val * 19) / 4095;
		}
	}
    HAL_ADC_Stop(&hadc);
    return tol;
}

// Funkcja ogarniająca wyświetlanie (UART + LCD)
void Update_Interface(uint16_t dist, uint16_t target, uint16_t tol, uint8_t detected)
{
    char buf_uart[100];
    char buf_lcd[32];

    // --- SERIAL MONITOR ---
    int len = sprintf(buf_uart, "Cel: %d +/- %d, \r\n Zmerzone: %d\r\n", target, tol, dist);
    HAL_UART_Transmit(&huart2, (uint8_t*)buf_uart, len, 100);

    // --- LCD LINIA 1 (Nastawy) ---
    lcd_put_cur(0, 0);
    sprintf(buf_lcd, "C:%3ucm +/- %2ucm ", target, tol);
    lcd_send_string(buf_lcd);

    // --- LCD LINIA 2 (Pomiar i Status) ---
    lcd_put_cur(1, 0);
    if (detected)
    {
        sprintf(buf_lcd, "Wykryto - %3ucm ", dist);
        lcd_send_string(buf_lcd);
    }
    else
    {
        lcd_send_string("                ");
    }
}
